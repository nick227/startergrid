/** V5 wire contract. Keep this module independent of Prisma and UI packages. */
export const DISTRIBUTION_CONTRACT_VERSION = 1 as const;
export type AutopilotMode = 'OFF' | 'ON' | 'PAUSED';
export type Qualification = 'VERIFIED_AUTOMATIC' | 'CONFIGURED_UNVERIFIED' | 'MANUAL' | 'PARTNER_ASSISTED' | 'UNAVAILABLE';
export type DistributionStatus =
  | 'NEEDS_SETUP' | 'NEEDS_VEHICLE_INFORMATION' | 'PROCESSING' | 'SUBMITTED'
  | 'VERIFIED_LIVE' | 'FAILED' | 'UNKNOWN' | 'HELD' | 'PAUSED' | 'EXCLUDED' | 'VERIFIED_REMOVED';
export type DistributionOperation = 'UPSERT' | 'WITHDRAW';
export type IncidentOwner = 'DEALERSHIP' | 'INTERNAL_SUPPORT' | 'SYSTEM' | 'PARTNER';
export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };

export interface AutopilotSafeguards {
  /** Fraction of the last verified price (0.3 means a 30% change). */
  maxPriceChangeFraction: number;
  minPriceCents: number;
  maxRemovalCount: number;
  minRemovalBatchSize: number;
  maxRemovalFraction: number;
  maxAttempts: number;
  retryBaseMs: number;
  retryMaxMs: number;
  verificationTimeoutMs: number;
  evidenceMaxAgeMs: number;
}

export interface AutopilotPolicy {
  dealershipId: string;
  mode: AutopilotMode;
  version: number;
  includedChannels: string[];
  excludedVehicleIds: string[];
  safeguards: AutopilotSafeguards;
  updatedAt: string;
  updatedBy: string;
}

export interface ChannelCapability {
  channel: string;
  qualification: Qualification;
  operations: DistributionOperation[];
  canVerify: boolean;
  reason: string;
  evidenceReference: string | null;
}

export interface VehicleSnapshot {
  dealershipId: string;
  vehicleId: string;
  /** Durable source revision: not an arrival timestamp generated by the worker. */
  sourceRevision: string;
  stockNumber: string;
  year: number;
  make: string;
  model: string;
  priceCents: number;
  listingStatus: 'DRAFT' | 'READY';
  sold: boolean;
  removed: boolean;
  photos: string[];
  details: { [key: string]: JsonValue };
}

export interface PublicationEvidence {
  channel: string;
  vehicleId: string;
  desiredHash: string;
  operation: DistributionOperation;
  method: 'OWNED_READ_MODEL' | 'PROVIDER_READBACK' | 'PROVIDER_WEBHOOK';
  observedAt: string;
  /** Authoritative destination observation, not submission acknowledgement. */
  result: 'LIVE' | 'REMOVED' | 'PENDING' | 'MISMATCH';
  reference: string;
}

export interface DistributionIncident {
  id: string;
  dealershipId: string;
  channel: string;
  vehicleId: string | null;
  batchId: string | null;
  reasonCode: string;
  severity: 'INFO' | 'WARNING' | 'CRITICAL';
  businessImpact: string;
  owner: IncidentOwner;
  ownerId: string | null;
  description: string;
  nextAction: string;
  technicalEvidence: { [key: string]: JsonValue };
  state: 'OPEN' | 'ACKNOWLEDGED' | 'RESOLVED';
  verificationState: 'UNVERIFIED' | 'VERIFIED';
  createdAt: string;
  updatedAt: string;
  resolvedAt: string | null;
}

export interface DistributionOutcome {
  dealershipId: string;
  vehicleId: string;
  channel: string;
  generation: number;
  desiredHash: string;
  operation: DistributionOperation;
  status: DistributionStatus;
  reasonCode: string | null;
  nextAction: string | null;
  owner: IncidentOwner;
  attemptCount: number;
  nextAttemptAt: string | null;
  submittedAt: string | null;
  evidence: PublicationEvidence | null;
  updatedAt: string;
}

export interface AutopilotSummary {
  contractVersion: typeof DISTRIBUTION_CONTRACT_VERSION;
  policy: AutopilotPolicy;
  capabilities: ChannelCapability[];
  coverage: 'OFF' | 'PAUSED' | 'FULL' | 'PARTIAL' | 'UNAVAILABLE';
  counts: Partial<Record<DistributionStatus, number>>;
  openIncidents: number;
  generatedAt: string;
}
