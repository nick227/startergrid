import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(repo, 'apps/web/src/docs');
const split = value => (value ?? '').split(',').map(item => item.trim()).filter(Boolean);
function collect(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    if (entry.name.startsWith('_')) return [];
    const path = join(directory, entry.name);
    return entry.isDirectory() ? collect(path) : entry.name.endsWith('.md') ? [path] : [];
  });
}
const records = collect(root).map(path => {
  const raw = readFileSync(path, 'utf8');
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) throw new Error(`Missing frontmatter: ${path}`);
  const frontmatter = Object.fromEntries(match[1].split('\n').filter(line => line.includes(':')).map(line => {
    const colon = line.indexOf(':');
    return [line.slice(0, colon).trim(), line.slice(colon + 1).trim()];
  }));
  const source = relative(root, path);
  return { id: frontmatter.id, source, frontmatter, body: match[2].trim() };
}).sort((a, b) => String(a.id).localeCompare(String(b.id)));
const ids = new Set();
const aliases = new Map();
for (const record of records) {
  const fm = record.frontmatter;
  for (const key of ['visibility', 'id', 'feature', 'type', 'audience', 'title', 'summary', 'tags', 'synonyms', 'updated']) {
    if (!fm[key]) throw new Error(`${record.source}: missing ${key}`);
  }
  if (fm.visibility !== 'public') throw new Error(`${record.source}: only explicitly public documentation may be published; move internal material outside apps/web/src/docs`);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(record.id) || ids.has(record.id)) throw new Error(`Invalid or duplicate ID: ${record.id}`);
  ids.add(record.id);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(fm.feature)) throw new Error(`Invalid feature ID: ${record.id}`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(fm.updated)) throw new Error(`Invalid review date: ${record.id}`);
  if (!['feature', 'task', 'troubleshooting', 'reference'].includes(fm.type)) throw new Error(`Invalid type: ${record.id}`);
  if (!split(fm.audience).every(value => ['user', 'staff', 'developer'].includes(value))) throw new Error(`Invalid audience: ${record.id}`);
  for (const alias of [record.source.replace(/\.md$/, ''), ...split(fm.aliases)]) {
    if (aliases.has(alias) && aliases.get(alias) !== record.id) throw new Error(`Duplicate alias: ${alias}`);
    aliases.set(alias, record.id);
  }
  for (const path of split(fm.implementation)) if (!existsSync(join(repo, path))) throw new Error(`Missing implementation reference: ${path}`);
}
for (const [alias, id] of aliases) if (ids.has(alias) && alias !== id) throw new Error(`Alias conflicts with ID: ${alias}`);
for (const record of records) {
  for (const id of [...split(record.frontmatter.related), ...[...record.body.matchAll(/\]\(doc:([^\s)]+)\)/g)].map(match => match[1])]) {
    if (!ids.has(id) && !aliases.has(id)) throw new Error(`${record.id}: unresolved relationship ${id}`);
  }
}
if (process.argv.includes('--write')) {
  writeFileSync(join(repo, 'apps/web/src/lib/docs/manifest.json'), JSON.stringify(records.map(({ body, ...record }) => record), null, 2) + '\n');
  writeFileSync(join(repo, 'apps/web/src/lib/docs/search-text.json'), JSON.stringify(Object.fromEntries(records.map(record => [record.id, record.body])), null, 2) + '\n');
  writeFileSync(join(repo, 'apps/web/src/lib/docs/loaders.ts'), '// Generated by scripts/export-documentation.mjs; public records only.\nexport const articleLoaders: Record<string, () => Promise<string>> = {\n' + records.map(record => `  ${JSON.stringify(record.id)}: () => import(${JSON.stringify('../../docs/' + record.source + '?raw')}).then(module => module.default),`).join('\n') + '\n};\n');
  console.log(`Indexed ${records.length} documentation records.`);
} else {
  console.log(JSON.stringify({ schemaVersion: 1, features: [...new Set(records.map(record => record.frontmatter.feature))].sort(), records }, null, 2));
}
